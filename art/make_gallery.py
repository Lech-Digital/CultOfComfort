"""Builds the review gallery from art/previews: a GitHub-viewable README.md, and optionally an HTML page with
thumbnails for the brainstorming companion (python3 art/make_gallery.py [companion_content_dir])."""
import os
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
PREVIEWS = os.path.join(HERE, "previews")

SECTIONS = [
    ("Scenes (real Unity renders)", ["board_landscape", "village_day", "village_night"], "scene"),
    ("Characters", ["prophet", "levy", "manatarms", "zealot", "cultist", "cultist_towel", "villager_woman", "friar_odo",
                    "lord_wulfric", "bishop", "blacksmith", "herbwife"], "model"),
    ("Creatures", ["pig", "sheep", "goat", "cow", "dog", "cat", "goose", "chicken"], "model"),
    ("Hearth and towers", ["hearth_l1", "hearth_l2", "hearth_l3", "sapling_flinger", "slurry_chute"], "model"),
    ("Village", ["woodcutter", "peat_cut", "cistern", "storage_hut", "cultist_hut", "well", "sauna"], "model"),
    ("Nature and props", ["pine", "oak", "birch", "dead_tree", "bush", "stump", "rock_a", "rock_b", "torch",
                          "spawn_gate", "props_barrels", "fence", "palisade", "wheelbarrow", "haycart", "scarecrow", "signpost",
                          "beehive", "campfire", "outhouse"], "model"),
    ("2024 junk", ["rubber_duck", "bathtub", "garden_chair", "shopping_trolley", "traffic_cone"], "model"),
    ("Battle effects", ["fx_mud_glob", "fx_splat", "fx_rock", "fx_hot_stone", "fx_hymnal", "fx_poof"], "model"),
]


def animations():
    folder = os.path.join(PREVIEWS, "anim")
    return sorted(f[:-4] for f in os.listdir(folder) if f.endswith(".gif")) if os.path.isdir(folder) else []


def readme():
    lines = ["# Art previews", "",
             "Generated by `./art/build.sh` (models), Unity's `AnimationShowcase` (GIFs) and `BoardScreenshot` (scenes). "
             "Rebuild this page with `python3 art/make_gallery.py`.", ""]
    for title, names, kind in SECTIONS:
        lines += [f"## {title}", ""]
        if kind == "scene":
            for n in names:
                if os.path.exists(os.path.join(PREVIEWS, f"{n}.png")):
                    lines += [f"**{n.replace('_', ' ')}**", "", f"![{n}]({n}.png)", ""]
            continue
        lines += ["| Model | Day | Night |", "|---|---|---|"]
        for n in names:
            if os.path.exists(os.path.join(PREVIEWS, f"{n}_day.png")):
                lines.append(f"| `{n}` | <img src=\"{n}_day.png\" width=\"220\"> | <img src=\"{n}_night.png\" width=\"220\"> |")
        lines.append("")
    lines += ["## Animations (code-driven, PartAnimator)", ""]
    for gif in animations():
        lines.append(f"<img src=\"anim/{gif}.gif\" width=\"200\" title=\"{gif}\">")
    with open(os.path.join(PREVIEWS, "README.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


def companion(content):
    thumbs = os.path.join(content, "gallery")
    os.makedirs(thumbs, exist_ok=True)

    def thumb(src, name, size):
        im = Image.open(src)
        im.thumbnail(size)
        im.convert("RGB").save(os.path.join(thumbs, name), quality=88)
        return f"/files/gallery/{name}"

    html = ["<h2>Good morning! Here is the night's work</h2>",
            "<p class=\"subtitle\">Everything below is generated by the pipeline: Blender scripts for the models, Unity for the scenes and "
            "animations. Click anything you want changed and tell me in the terminal.</p>"]
    for title, names, kind in SECTIONS:
        html.append(f"<h3 style=\"margin-top:22px\">{title}</h3>")
        html.append("<div style=\"display:grid;grid-template-columns:repeat(auto-fill,minmax(%s,1fr));gap:10px\">"
                    % ("480px" if kind == "scene" else "170px"))
        for n in names:
            if kind == "scene":
                src = os.path.join(PREVIEWS, f"{n}.png")
                if os.path.exists(src):
                    html.append(f"<div><div class=\"label\">{n.replace('_', ' ')}</div><img src=\"{thumb(src, n + '.jpg', (960, 960))}\" "
                                f"style=\"width:100%;border-radius:10px\"></div>")
                continue
            src = os.path.join(PREVIEWS, f"{n}_day.png")
            if os.path.exists(src):
                html.append(f"<div class=\"option\" data-choice=\"{n}\" onclick=\"toggleSelect(this)\" style=\"display:block;padding:6px\">"
                            f"<img src=\"{thumb(src, n + '.jpg', (340, 340))}\" style=\"width:100%;border-radius:8px\">"
                            f"<div class=\"label\" style=\"margin-top:4px\">{n.replace('_', ' ')}</div></div>")
        html.append("</div>")
    html.append("<h3 style=\"margin-top:22px\">Animations</h3><div style=\"display:grid;grid-template-columns:repeat(auto-fill,minmax(190px,1fr));gap:10px\">")
    for gif in animations():
        src = os.path.join(PREVIEWS, "anim", f"{gif}.gif")
        dst = os.path.join(thumbs, f"{gif}.gif")
        with open(src, "rb") as a, open(dst, "wb") as b:
            b.write(a.read())
        html.append(f"<div><div class=\"label\">{gif.replace('_', ' ')}</div><img src=\"/files/gallery/{gif}.gif\" style=\"width:100%;border-radius:8px\"></div>")
    html.append("</div>")
    with open(os.path.join(content, "morning-gallery.html"), "w") as f:
        f.write("\n".join(html))


if __name__ == "__main__":
    readme()
    if len(sys.argv) > 1:
        companion(sys.argv[1])
    print("gallery written")
